// The names a host uses with a file, and the TypeScript module `nudg generate` writes for
// them, so a host can't misspell a target, event, input or state.

import { handledEvents } from "./observe.ts";
import { createRuntime } from "./runtime.ts";
import type { Machine, Program } from "./types.ts";

/** The names a file exposes to its host, in file order. */
export interface Contract {
  /** Targets to bind elements or views to. */
  targets: string[];
  /** Events the file handles: app events (`host.check`, all declared ones when the file declares "host") and the targets' own (`track.tap`). */
  events: string[];
  /** Continuous inputs the file reads with `map` or `follow` (layout measurements excluded). */
  inputs: string[];
  /** State paths, as `state` reports them and the `state` option accepts, e.g. "open/expanded". */
  states: string[];
}

export function contract(program: Program): Contract {
  const states: string[] = [];
  const walk = (machine: Machine, prefix: string) => {
    if (machine.kind === "regions") {
      for (const [name, region] of machine.regions) walk(region, prefix + name + "/");
      return;
    }
    for (const [name, state] of machine.states) {
      states.push(prefix + name);
      if (state.machine) walk(state.machine, prefix + name + "/");
    }
  };
  walk(program.machine, "");
  const events = [...handledEvents(program)];
  const inputs = createRuntime(program).requiredInputs();
  // A declared host (v0.13) is the contract for app names, including ones no state handles yet.
  const own = (names: string[]) => names.filter((name) => !name.startsWith("host."));
  const host = program.host;
  return {
    targets: [...program.targets],
    events: host ? [...own(events), ...host.events.map((name) => `host.${name}`)] : events,
    inputs: host ? [...own(inputs), ...[...host.inputs.keys()].map((name) => `host.${name}`)] : inputs,
    states,
  };
}

/** The TypeScript type name for a file: "toggle-drag.nudg.json" becomes "ToggleDragContract". */
export function contractName(file: string): string {
  const base = (file.split(/[\\/]/).pop() ?? file).replace(/(\.nudg)?\.json$/, "");
  const words = base.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const name = words.map((w) => w[0].toUpperCase() + w.slice(1)).join("") || "Nudg";
  return (/^[0-9]/.test(name) ? "Nudg" + name : name) + "Contract";
}

/**
 * The module `nudg generate` writes beside a file. Types only, so it costs nothing at run
 * time and works with any bundler: `useNudg<ToggleContract>(toggle)`. Regenerating from an
 * unchanged contract gives the same text, which is how `--check` finds stale modules.
 */
export function contractModule(c: Contract, file: string): string {
  const union = (names: string[]) => (names.length ? names.map((n) => JSON.stringify(n)).join(" | ") : "never");
  return `// Generated by \`nudg generate\` from ${file.split(/[\\/]/).pop()}; do not edit.
// Regenerate after changing the file; \`nudg generate --check\` fails while this is stale.

export interface ${contractName(file)} {
  targets: ${union(c.targets)};
  events: ${union(c.events)};
  inputs: ${union(c.inputs)};
  states: ${union(c.states)};
}
`;
}
