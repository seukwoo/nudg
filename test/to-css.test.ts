// nudg to-css: a file as plain CSS, checked against the runtime; and on a real page, the CSS
// the browser plays matches the runtime (Chrome; skipped without one).

import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import { toProgram } from "../src/core/to-program.ts";
import { toCss } from "../src/core/to-css.ts";
import { createRuntime } from "../src/core/runtime.ts";
import { hexToOklab } from "../src/core/color.ts";
import { findChrome } from "../src/node/chrome.ts";

const example = (name: string) => toProgram(JSON.parse(readFileSync(`examples/${name}.nudg.json`, "utf8")));

const SIDE_MENU = toProgram({
  nudg: "1.5",
  host: { events: ["show", "hide"] },
  targets: ["menu", "dim"],
  values: { "menu.x": { measure: "menu.width", times: -1 }, "dim.opacity": 0 },
  animate: { "menu.x": { tween: { duration: 0.22, ease: [0.2, 0.9, 0.25, 1.05] } }, "dim.opacity": { tween: { duration: 0.18, ease: "out" } } },
  initial: "hidden",
  states: {
    hidden: { when: { "host.show": "shown" } },
    shown: { set: { "menu.x": 0, "dim.opacity": 1 }, when: { "host.hide": { to: "hidden", animate: { "menu.x": { tween: { duration: 0.16, ease: "in" } }, "dim.opacity": { tween: { duration: 0.16, ease: "in" } } } } } },
  },
});

test("a side menu that mounts in and closes on an attribute: @starting-style, a rule for the closed state, own-width percentages", () => {
  const r = toCss(SIDE_MENU, { mount: "host.show", states: { hidden: "[data-closing]" }, targets: { menu: ".lnb", dim: ".lnb-dim" } });
  assert.deepEqual(r.problems, []);
  assert.deepEqual(r.differences, []);
  assert.deepEqual(r.lost, []);
  assert.match(r.css, /\.lnb \{\n  translate: 0px 0px;\n  transition: translate 0\.22s cubic-bezier\(0\.2, 0\.9, 0\.25, 1\.05\);\n\}/);
  assert.match(r.css, /@starting-style \{\n  \.lnb \{\n    translate: -100% 0px;/);
  assert.match(r.css, /:is\(\[data-closing\]\) \.lnb, \.lnb:is\(\[data-closing\]\) \{\n  translate: -100% 0px;\n  transition: translate 0\.16s cubic-bezier\(0\.42, 0, 1, 1\);/);
  assert.match(r.css, /^\/\* Generated by nudg/);
  assert.match(r.css, /prefers-reduced-motion/);
});

test("hover and press become :hover and :active; one transition list on the element when timings don't depend on the state", () => {
  const r = toCss(example("hover-card"));
  assert.deepEqual(r.differences, []);
  assert.match(r.css, /\[data-nudg="card"\]:hover \{\n  translate: 0px -6px;\n\}/);
  assert.match(r.css, /\[data-nudg="card"\]:active \{\n  scale: 0\.97;\n\}/);
  assert.match(r.css, /transition: translate 0\.\d+s linear\(0, [^)]+, 1\), scale/);
});

test("what CSS can't do is reported: a timing that depends on where it came from, layout from another element", () => {
  const checkbox = toCss(example("checkbox"));
  assert.ok(checkbox.differences.length > 0);
  assert.ok(checkbox.lost.some((l) => /differently from/.test(l)));
  const drawer = toCss(example("drawer"));
  assert.equal(drawer.css, "");
  assert.match(drawer.problems[0], /depends on drawer's measured width/);
  const spinner = toCss(example("spinner"));
  assert.ok(spinner.lost.some((l) => /loops/.test(l)));
});

const chrome = findChrome();

test("in Chrome, the generated CSS plays as the runtime does: a spring as linear(), a color blended in OKLab", { skip: chrome ? false : "no Chrome found" }, async () => {
  const { launchBrowser, waitFor } = await import("../src/node/cdp.ts");
  const { serveIfLocal } = await import("../src/node/observe.ts");
  const program = example("toggle");
  const { css } = toCss(program);
  const { url, close } = await serveIfLocal("test/fixtures/host/presence.html");
  const browser = await launchBrowser(chrome!);
  try {
    await browser.send("Page.navigate", { url });
    await waitFor(() => browser.evaluate("window.__player ? 'ready' : ''"), 15_000);
    const times = [0.03, 0.08, 0.15, 0.25, 0.4];
    const samples = (await browser.evaluate(`(async () => {
      window.__player.destroy();
      document.body.innerHTML = '<div id="box"><div data-nudg="track" style="width:44px;height:24px"><div data-nudg="knob" style="width:20px;height:20px"></div></div></div>';
      const style = document.createElement("style");
      style.textContent = ${JSON.stringify(css)};
      document.head.append(style);
      await new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)));
      document.getElementById("box").setAttribute("data-nudg-state", "on");
      getComputedStyle(document.querySelector('[data-nudg="knob"]')).translate;
      const animations = document.getAnimations();
      for (const a of animations) a.pause();
      const out = [];
      for (const t of ${JSON.stringify(times)}) {
        for (const a of animations) a.currentTime = t * 1000;
        out.push({ x: getComputedStyle(document.querySelector('[data-nudg="knob"]')).translate, color: getComputedStyle(document.querySelector('[data-nudg="track"]')).backgroundColor });
      }
      return JSON.stringify({ count: animations.length, out });
    })()`)) as string;
    const { count, out } = JSON.parse(samples) as { count: number; out: { x: string; color: string }[] };
    assert.equal(count, 2, "a transition for the knob and one for the track");
    const rt = createRuntime(program);
    rt.send("track.tap", 0);
    times.forEach((t, i) => {
      const v = rt.sample(t);
      const x = parseFloat(out[i].x);
      assert.ok(Math.abs(x - (v["knob.x"] as number)) < 0.5, `knob.x at ${t}s: CSS ${out[i].x}, nudg ${v["knob.x"]}`);
      const m = /oklab\(([-\d.e]+) ([-\d.e]+) ([-\d.e]+)/.exec(out[i].color);
      assert.ok(m, `track color at ${t}s is blended in OKLab: ${out[i].color}`);
      const want = hexToOklab(v["track.color"] as string);
      const d = Math.hypot(Number(m![1]) - want[0], Number(m![2]) - want[1], Number(m![3]) - want[2]);
      assert.ok(d < 0.01, `track color at ${t}s: CSS ${out[i].color}, nudg ${v["track.color"]}`);
    });
  } finally {
    await browser.close();
    close();
  }
});

test("the audit counts CSS that to-css wrote as on nudg, and counts it again once hand-edited", async () => {
  const { audit } = await import("../src/node/audit.ts");
  const { css } = toCss(SIDE_MENU, { mount: "host.show", file: "menu.nudg.json" });
  const generated = audit([{ path: "menu.css", text: css + "\n.x { transition: transform 0.2s; }" }]);
  assert.equal(generated.findings.length, 0);
  assert.equal(generated.coverage, 100);
  const edited = audit([{ path: "menu.css", text: css.replace(/^\/\*.*\*\/\n/, "") + "\n.x { transition: transform 0.2s; }" }]);
  assert.ok(edited.findings.length > 1, "its transitions are outside nudg again");
});

test("a map from a scroll offset becomes a scroll-driven animation, checked point by point", () => {
  const r = toCss(example("scroll-header"));
  assert.deepEqual(r.differences, []);
  assert.ok(!r.lost.some((l) => /scroll/.test(l)));
  assert.match(r.css, /\[data-nudg="scroller"\] \{\n  scroll-timeline: --nudg-scroller-y block;/);
  assert.match(r.css, /@keyframes nudg-accent-scroller-y \{\n  0% \{ scale: 1; opacity: 1; \}\n  62\.5% \{ scale: 0\.7188 1; opacity: 0\.4; \}/);
  assert.match(r.css, /@supports \(animation-timeline: scroll\(\)\)/);
});

test("in Chrome, a scroll-driven map follows the scroll as the runtime's map does", { skip: chrome ? false : "no Chrome found" }, async () => {
  const { launchBrowser, waitFor } = await import("../src/node/cdp.ts");
  const { serveIfLocal } = await import("../src/node/observe.ts");
  const program = example("scroll-header");
  const { css } = toCss(program);
  const { url, close } = await serveIfLocal("test/fixtures/host/presence.html");
  const browser = await launchBrowser(chrome!);
  try {
    await browser.send("Page.navigate", { url });
    await waitFor(() => browser.evaluate("window.__player ? 'ready' : ''"), 15_000);
    const offsets = [0, 25, 50, 65, 80, 140];
    const read = JSON.parse((await browser.evaluate(`(async () => {
      window.__player.destroy();
      document.body.innerHTML = '<div data-nudg="header" style="width:200px"><div data-nudg="accent" style="height:4px"></div></div><div data-nudg="scroller" style="height:100px;overflow:auto"><div style="height:1000px"></div></div>';
      const style = document.createElement("style");
      style.textContent = ${JSON.stringify(css)};
      document.head.append(style);
      const scroller = document.querySelector('[data-nudg="scroller"]');
      const frame = () => new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)));
      const out = [];
      for (const y of ${JSON.stringify(offsets)}) {
        scroller.scrollTop = y;
        await frame();
        out.push({ height: getComputedStyle(document.querySelector('[data-nudg="header"]')).height, opacity: getComputedStyle(document.querySelector('[data-nudg="accent"]')).opacity });
      }
      return JSON.stringify(out);
    })()`)) as string) as { height: string; opacity: string }[];
    offsets.forEach((y, i) => {
      const rt = createRuntime(program);
      rt.input("scroller.scroll.y", y, 0);
      const v = rt.sample(0);
      assert.ok(Math.abs(parseFloat(read[i].height) - (v["header.height"] as number)) < 0.5, `header.height at ${y}px: CSS ${read[i].height}, nudg ${v["header.height"]}`);
      assert.ok(Math.abs(parseFloat(read[i].opacity) - (v["accent.opacity"] as number)) < 0.01, `accent.opacity at ${y}px: CSS ${read[i].opacity}, nudg ${v["accent.opacity"]}`);
    });
  } finally {
    await browser.close();
    close();
  }
});

test("in Chrome, --script plays the file on nudg's runtime: it follows the page's own attribute, and a drag CSS can't do comes back", { skip: chrome ? false : "no Chrome found" }, async () => {
  const { writeFileSync, rmSync, mkdirSync } = await import("node:fs");
  const { launchBrowser, waitFor } = await import("../src/node/cdp.ts");
  const { serveIfLocal } = await import("../src/node/observe.ts");
  const dir = "test/fixtures/host/.to-css";
  mkdirSync(dir, { recursive: true });
  const sources = { player: "/dist/dom/play.js", programs: "/dist/core/program-json.js" };
  const menu = toCss(SIDE_MENU, { mount: "host.show", states: { hidden: "[data-closing]" }, targets: { menu: ".lnb", dim: ".lnb-dim" }, file: "menu.nudg.json", script: sources });
  const carousel = toCss(example("carousel"), { file: "carousel.nudg.json", script: sources });
  assert.ok(carousel.lost.some((l) => /nearest/.test(l)), "CSS alone loses the snap");
  writeFileSync(`${dir}/menu.css`, menu.css);
  writeFileSync(`${dir}/menu.nudg.js`, menu.script!);
  writeFileSync(`${dir}/carousel.css`, carousel.css);
  writeFileSync(`${dir}/carousel.nudg.js`, carousel.script!);
  writeFileSync(`${dir}/page.html`, `<!doctype html><html><head>
    <script>document.documentElement.setAttribute("data-nudg-live", "")</script>
    <link rel="stylesheet" href="menu.css"><link rel="stylesheet" href="carousel.css">
    <style>.lnb { width: 200px; height: 100px; background: #333; } .lnb-dim { width: 50px; height: 50px; }
      .viewport { width: 200px; overflow: hidden; } [data-nudg=strip] { display: flex; width: 600px; height: 60px; } [data-nudg=strip] > div { flex: none; width: 200px; }
      [data-nudg^=dot] { width: 10px; height: 10px; }</style>
    </head><body>
    <div class="lnb-dim" id="dim"><div class="lnb"></div></div>
    <div class="viewport"><div data-nudg="strip"><div>1</div><div>2</div><div>3</div></div></div>
    <div data-nudg="dot1"></div><div data-nudg="dot2"></div><div data-nudg="dot3"></div>
    <script type="module">
      const [m, c] = await Promise.all([import("./menu.nudg.js"), import("./carousel.nudg.js")]);
      window.__players = { menu: m.player, carousel: c.player };
    </script></body></html>`);
  const { url, close } = await serveIfLocal(`${dir}/page.html`);
  const browser = await launchBrowser(chrome!);
  try {
    await browser.send("Page.navigate", { url });
    await waitFor(() => browser.evaluate("window.__players ? 'ready' : ''"), 15_000);
    await new Promise((r) => setTimeout(r, 600));
    const shown = JSON.parse(await browser.evaluate(`JSON.stringify({ state: __players.menu.runtime.state(), transform: getComputedStyle(document.querySelector(".lnb")).transform, translate: getComputedStyle(document.querySelector(".lnb")).translate })`));
    assert.deepEqual(shown.state, ["shown"], "mounted with host.show");
    assert.equal(shown.translate, "none", "the CSS is off while the script runs");
    await browser.evaluate(`document.getElementById("dim").setAttribute("data-closing", "")`);
    await new Promise((r) => setTimeout(r, 500));
    const closed = JSON.parse(await browser.evaluate(`JSON.stringify({ state: __players.menu.runtime.state(), x: new DOMMatrix(getComputedStyle(document.querySelector(".lnb")).transform).m41 })`));
    assert.deepEqual(closed.state, ["hidden"], "the page's own attribute sends the file's event");
    assert.ok(Math.abs(closed.x + 200) < 0.5, `slid out by its own width: ${closed.x}`);
    // A drag and release: the strip snaps to the next slide, as the file says.
    const r = JSON.parse(await browser.evaluate(`JSON.stringify(document.querySelector("[data-nudg=strip]").getBoundingClientRect())`));
    const y = r.y + 30;
    const mouse = (type: string, x: number) => browser.send("Input.dispatchMouseEvent", { type, x, y, button: "left", buttons: type === "mouseReleased" ? 0 : 1, clickCount: 1 });
    await mouse("mousePressed", 180);
    for (let i = 1; i <= 8; i++) {
      await mouse("mouseMoved", 180 - i * 15);
      await new Promise((r) => setTimeout(r, 16));
    }
    await mouse("mouseReleased", 60);
    await new Promise((r) => setTimeout(r, 900));
    assert.deepEqual(JSON.parse(await browser.evaluate(`JSON.stringify(__players.carousel.runtime.state())`)), ["second"]);
  } finally {
    await browser.close();
    close();
    rmSync(dir, { recursive: true, force: true });
  }
});
