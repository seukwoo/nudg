// nudg to-css: a file as plain CSS, checked against the runtime; and on a real page, the CSS
// the browser plays matches the runtime (Chrome; skipped without one).

import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import { toProgram } from "../src/core/to-program.ts";
import { toCss } from "../src/core/to-css.ts";
import { createRuntime } from "../src/core/runtime.ts";
import { hexToOklab } from "../src/core/color.ts";
import { findChrome } from "../src/node/chrome.ts";

const example = (name: string) => toProgram(JSON.parse(readFileSync(`examples/${name}.nudg.json`, "utf8")));

const SIDE_MENU = toProgram({
  nudg: "1.5",
  host: { events: ["show", "hide"] },
  targets: ["menu", "dim"],
  values: { "menu.x": { measure: "menu.width", times: -1 }, "dim.opacity": 0 },
  animate: { "menu.x": { tween: { duration: 0.22, ease: [0.2, 0.9, 0.25, 1.05] } }, "dim.opacity": { tween: { duration: 0.18, ease: "out" } } },
  initial: "hidden",
  states: {
    hidden: { when: { "host.show": "shown" } },
    shown: { set: { "menu.x": 0, "dim.opacity": 1 }, when: { "host.hide": { to: "hidden", animate: { "menu.x": { tween: { duration: 0.16, ease: "in" } }, "dim.opacity": { tween: { duration: 0.16, ease: "in" } } } } } },
  },
});

test("a side menu that mounts in and closes on an attribute: @starting-style, a rule for the closed state, own-width percentages", () => {
  const r = toCss(SIDE_MENU, { mount: "host.show", states: { hidden: "[data-closing]" }, targets: { menu: ".lnb", dim: ".lnb-dim" } });
  assert.deepEqual(r.problems, []);
  assert.deepEqual(r.differences, []);
  assert.deepEqual(r.lost, []);
  assert.match(r.css, /\.lnb \{\n  translate: 0px 0px;\n  transition: translate 0\.22s cubic-bezier\(0\.2, 0\.9, 0\.25, 1\.05\);\n\}/);
  assert.match(r.css, /@starting-style \{\n  \.lnb \{\n    translate: -100% 0px;/);
  assert.match(r.css, /:is\(\[data-closing\]\) \.lnb, \.lnb:is\(\[data-closing\]\) \{\n  translate: -100% 0px;\n  transition: translate 0\.16s cubic-bezier\(0\.42, 0, 1, 1\);/);
  assert.match(r.css, /^\/\* Generated by nudg/);
  assert.match(r.css, /prefers-reduced-motion/);
});

test("hover and press become :hover and :active; one transition list on the element when timings don't depend on the state", () => {
  const r = toCss(example("hover-card"));
  assert.deepEqual(r.differences, []);
  assert.match(r.css, /\[data-nudg="card"\]:hover \{\n  translate: 0px -6px;\n\}/);
  assert.match(r.css, /\[data-nudg="card"\]:active \{\n  scale: 0\.97;\n\}/);
  assert.match(r.css, /transition: translate 0\.\d+s linear\(0, [^)]+, 1\), scale/);
});

test("what CSS can't do is reported: a timing that depends on where it came from, layout from another element", () => {
  const checkbox = toCss(example("checkbox"));
  assert.ok(checkbox.differences.length > 0);
  assert.ok(checkbox.lost.some((l) => /differently from/.test(l)));
  const drawer = toCss(example("drawer"));
  assert.equal(drawer.css, "");
  assert.match(drawer.problems[0], /depends on drawer's measured width/);
  const spinner = toCss(example("spinner"));
  assert.ok(spinner.lost.some((l) => /loops/.test(l)));
});

const chrome = findChrome();

test("in Chrome, the generated CSS plays as the runtime does: a spring as linear(), a color blended in OKLab", { skip: chrome ? false : "no Chrome found" }, async () => {
  const { launchBrowser, waitFor } = await import("../src/node/cdp.ts");
  const { serveIfLocal } = await import("../src/node/observe.ts");
  const program = example("toggle");
  const { css } = toCss(program);
  const { url, close } = await serveIfLocal("test/fixtures/host/presence.html");
  const browser = await launchBrowser(chrome!);
  try {
    await browser.send("Page.navigate", { url });
    await waitFor(() => browser.evaluate("window.__player ? 'ready' : ''"), 15_000);
    const times = [0.03, 0.08, 0.15, 0.25, 0.4];
    const samples = (await browser.evaluate(`(async () => {
      window.__player.destroy();
      document.body.innerHTML = '<div id="box"><div data-nudg="track" style="width:44px;height:24px"><div data-nudg="knob" style="width:20px;height:20px"></div></div></div>';
      const style = document.createElement("style");
      style.textContent = ${JSON.stringify(css)};
      document.head.append(style);
      await new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)));
      document.getElementById("box").setAttribute("data-nudg-state", "on");
      getComputedStyle(document.querySelector('[data-nudg="knob"]')).translate;
      const animations = document.getAnimations();
      for (const a of animations) a.pause();
      const out = [];
      for (const t of ${JSON.stringify(times)}) {
        for (const a of animations) a.currentTime = t * 1000;
        out.push({ x: getComputedStyle(document.querySelector('[data-nudg="knob"]')).translate, color: getComputedStyle(document.querySelector('[data-nudg="track"]')).backgroundColor });
      }
      return JSON.stringify({ count: animations.length, out });
    })()`)) as string;
    const { count, out } = JSON.parse(samples) as { count: number; out: { x: string; color: string }[] };
    assert.equal(count, 2, "a transition for the knob and one for the track");
    const rt = createRuntime(program);
    rt.send("track.tap", 0);
    times.forEach((t, i) => {
      const v = rt.sample(t);
      const x = parseFloat(out[i].x);
      assert.ok(Math.abs(x - (v["knob.x"] as number)) < 0.5, `knob.x at ${t}s: CSS ${out[i].x}, nudg ${v["knob.x"]}`);
      const m = /oklab\(([-\d.e]+) ([-\d.e]+) ([-\d.e]+)/.exec(out[i].color);
      assert.ok(m, `track color at ${t}s is blended in OKLab: ${out[i].color}`);
      const want = hexToOklab(v["track.color"] as string);
      const d = Math.hypot(Number(m![1]) - want[0], Number(m![2]) - want[1], Number(m![3]) - want[2]);
      assert.ok(d < 0.01, `track color at ${t}s: CSS ${out[i].color}, nudg ${v["track.color"]}`);
    });
  } finally {
    await browser.close();
    close();
  }
});

test("the audit counts CSS that to-css wrote as on nudg, and counts it again once hand-edited", async () => {
  const { audit } = await import("../src/node/audit.ts");
  const { css } = toCss(SIDE_MENU, { mount: "host.show", file: "menu.nudg.json" });
  const generated = audit([{ path: "menu.css", text: css + "\n.x { transition: transform 0.2s; }" }]);
  assert.equal(generated.findings.length, 0);
  assert.equal(generated.coverage, 100);
  const edited = audit([{ path: "menu.css", text: css.replace(/^\/\*.*\*\/\n/, "") + "\n.x { transition: transform 0.2s; }" }]);
  assert.ok(edited.findings.length > 1, "its transitions are outside nudg again");
});
